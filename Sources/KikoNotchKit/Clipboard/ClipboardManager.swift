import Foundation
import AppKit
import Combine

/// Manager tracking pasteboard changes with concealed password exclusion.
/// Implements CLIP-001, CLIP-003, CLIP-004, and SEC-003.
@MainActor
public final class ClipboardManager: ObservableObject {
    public static let shared = ClipboardManager()
    
    @Published public private(set) var items: [ClipboardItem] = []
    @Published public var isMonitoring: Bool = false
    
    private var lastChangeCount: Int = 0
    private var timer: Timer?
    private let storage: ClipboardStorage
    
    // Concealed pasteboard types used by 1Password, Bitwarden, Apple Keychain
    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("com.apple.find.pasteboard")
    ]
    
    public init(storage: ClipboardStorage = .shared) {
        self.storage = storage
        self.items = storage.getAll()
        self.lastChangeCount = NSPasteboard.general.changeCount
    }
    
    public func start() {
        guard !isMonitoring else { return }
        isMonitoring = true
        lastChangeCount = NSPasteboard.general.changeCount
        
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkForChanges()
            }
        }
    }
    
    public func stop() {
        guard isMonitoring else { return }
        isMonitoring = false
        timer?.invalidate()
        timer = nil
    }
    
    public func checkForChanges() {
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount
        
        // Check for password manager concealed types (CLIP-004)
        if let types = pasteboard.types {
            for concealed in concealedTypes {
                if types.contains(concealed) {
                    // Ignore password/transient data
                    return
                }
            }
        }
        
        // Check for file URLs first
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], let firstUrl = urls.first {
            let item = ClipboardItem(text: firstUrl.path, fileURL: firstUrl)
            storage.add(item)
            self.items = storage.getAll()
            return
        }
        
        // Extract text
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return }
        
        // Input sanitization (SEC-003) - trim excessive whitespace/control chars
        let sanitized = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !sanitized.isEmpty else { return }
        
        let item = ClipboardItem(text: sanitized)
        storage.add(item)
        self.items = storage.getAll()
    }
    
    /// Copies chosen item back onto active system pasteboard (CLIP-003).
    public func copyBackToPasteboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let fileURL = item.fileURL {
            pasteboard.writeObjects([fileURL as NSURL])
        } else {
            pasteboard.setString(item.text, forType: .string)
        }
        self.lastChangeCount = pasteboard.changeCount
    }
    
    /// Wipes all clipboard history immediately (CLIP-004).
    public func clearAllHistory() {
        storage.clearAll()
        self.items = []
    }
}
